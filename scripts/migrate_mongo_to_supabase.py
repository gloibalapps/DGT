#!/usr/bin/env python3
"""One-off copy of every MongoDB collection into Supabase Postgres.

NOT run as part of the migration branch. Run once, after applying
supabase/migrations/0001_init.sql, while the old backend is in read-only /
maintenance mode:

    pip install -r scripts/requirements.txt
    export MONGO_URL=... DB_NAME=...                # old Emergent Mongo
    export SUPABASE_URL=https://<ref>.supabase.co
    export SUPABASE_SERVICE_ROLE_KEY=...            # service role (bypasses RLS)
    python scripts/migrate_mongo_to_supabase.py --dry-run   # counts only
    python scripts/migrate_mongo_to_supabase.py              # copy
    python scripts/migrate_mongo_to_supabase.py --truncate   # wipe targets first (re-run)

Each Mongo document is written as-is into the table's `doc` jsonb column
(`_id` dropped, datetimes -> ISO-8601 UTC strings); the key columns are
generated by Postgres. Rows are inserted in batches; unique-key conflicts
(e.g. a re-run) are skipped with --skip-existing.
"""
import argparse
import json
import os
import sys
from datetime import date, datetime, timezone

from bson import ObjectId
from pymongo import MongoClient
from supabase import create_client

COLLECTIONS = ["users", "user_sessions", "oauth_states", "waitlist", "profiles", "vehicles",
               "trips", "income", "expenses", "shifts", "drive_tokens", "ue_jobs"]
# natural unique key per table (for --skip-existing)
KEYS = {"users": "user_id", "user_sessions": "session_token", "oauth_states": "state",
        "waitlist": "email", "profiles": "profile_id", "drive_tokens": "profile_id"}
SKIP = {"oauth_states"}  # transient (10-minute TTL); not worth copying
BATCH = 200


def to_json(v):
    if isinstance(v, datetime):
        if v.tzinfo is None:
            v = v.replace(tzinfo=timezone.utc)
        return v.isoformat()
    if isinstance(v, date):
        return v.isoformat()
    if isinstance(v, ObjectId):
        return str(v)
    if isinstance(v, dict):
        return {k: to_json(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [to_json(x) for x in v]
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--truncate", action="store_true")
    ap.add_argument("--skip-existing", action="store_true")
    a = ap.parse_args()

    mongo = MongoClient(os.environ["MONGO_URL"])[os.environ["DB_NAME"]]
    sb = None if a.dry_run else create_client(os.environ["SUPABASE_URL"], os.environ["SUPABASE_SERVICE_ROLE_KEY"])
    total = 0
    for name in COLLECTIONS:
        n_src = mongo[name].estimated_document_count()
        if name in SKIP or a.dry_run:
            print(f"{name:14s} source={n_src}{'  (skipped)' if name in SKIP else ''}")
            continue
        if a.truncate:
            sb.table(name).delete().gte("_pk", 0).execute()
        key = KEYS.get(name, "id")
        if name == "user_sessions":  # drop expired sessions
            now = datetime.now(timezone.utc)
            cur = mongo[name].find({"$or": [{"expires_at": {"$gt": now}}, {"expires_at": {"$exists": False}}]})
        else:
            cur = mongo[name].find({})
        batch, seen, written = [], set(), 0

        def flush():
            nonlocal batch, written
            if not batch:
                return
            if a.skip_existing:
                ids = [b["doc"].get(key) for b in batch if b["doc"].get(key) is not None]
                have = {r[key] for r in sb.table(name).select(key).in_(key, ids).execute().data} if ids else set()
                batch = [b for b in batch if b["doc"].get(key) not in have]
            if batch:
                sb.table(name).insert(batch).execute()
                written += len(batch)
            batch = []

        for d in cur:
            d.pop("_id", None)
            d = to_json(d)
            k = d.get(key)
            if k is not None:  # Mongo had no unique index on most of these; keep first copy
                if k in seen:
                    print(f"  ! duplicate {name}.{key}={k} skipped", file=sys.stderr)
                    continue
                seen.add(k)
            batch.append({"doc": json.loads(json.dumps(d))})
            if len(batch) >= BATCH:
                flush()
        flush()
        total += written
        n_dst = sb.table(name).select("_pk", count="exact").limit(1).execute().count
        print(f"{name:14s} source={n_src} written={written} target_total={n_dst}"
              f"{'  <-- MISMATCH' if n_dst != n_src else ''}")
    print("done, rows written:", total)


if __name__ == "__main__":
    main()
