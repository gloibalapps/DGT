export const AU_KB = `=== AUSTRALIA — ATO guidance for rideshare & delivery drivers (source of truth) ===

SCOURCE: Australian Taxation Office (ATO) — "Income and deductions for
ride-sourcing" and "Motor vehicle expenses" guidance.

A. CAR EXPENSE METHODS (choose ONE per car, per financial year)
1. Cents per kilometre method
   - Rate: 88 cents per business km for the 2024–25 financial year (85c for 2023–24). Updated yearly by the ATO.
   - Capped at 5,000 business km per car, per year.
   - No receipts required, but you must be able to show how you calculated your business km (e.g. diary/records).
   - The single rate already includes decline in value (depreciation), fuel, registration, insurance, servicing and repairs — you cannot claim these separately on top.
2. Logbook method
   - Keep a logbook for 12 continuous weeks that is representative of the year; it is valid for 5 years.
   - Work out your business-use percentage from the logbook.
   - Claim that percentage of ACTUAL running costs: fuel, oil, registration, insurance, servicing, repairs, tyres, interest on a car loan, lease payments, and decline in value (depreciation) of the car.
   - You also need odometer readings for the start and end of the year.

B. WHAT IS CLAIMABLE (work-related portion only)
   - Car running costs via cents-per-km OR logbook (see above).
   - Tolls and parking fees incurred while working (claimable in addition to the cents-per-km or logbook car claim).
   - Mobile phone and internet — the work-related percentage of your bill.
   - Fees/commissions charged by the platform (e.g. Uber/DoorDash service fees).
   - Bank fees on an account used for the business.
   - Car cleaning/washing (work-related portion), and consumables like water/mints for passengers.
   - Amenities for passengers, phone mount, in-car charger (work-related portion; higher-cost items may need to be depreciated).
   - Tax agent fees (deductible the following year).
   - Sunglasses/sun protection can be claimable for drivers exposed to sun while working (work-related portion).

C. WHAT IS NOT CLAIMABLE
   - The private-use portion of any expense.
   - The full purchase price of the car in one year (a car is claimed over time via decline in value / the cents-per-km or logbook method).
   - Fines and penalties (parking fines, speeding/traffic infringements).
   - Normal private travel and the private portion of trips.
   - Fuel/car costs claimed separately when you have already used the cents-per-km method (they're already included in the rate).
   - Ordinary clothing (only occupation-specific or protective clothing is deductible).
   - Meals and coffee for yourself while driving (generally private).
   - The GST portion of an expense IF you are registered for GST (you claim that GST as a credit on your BAS instead, and your income-tax deductions are GST-exclusive).

D. GST
   - Ride-sourcing (carrying passengers) is treated like taxi travel: you MUST register for GST from the first dollar, regardless of turnover.
   - Food/parcel delivery only: you register for GST only if your turnover reaches $75,000 or more.
   - If registered: report income and GST on your Business Activity Statement (BAS); you can claim GST credits on business expenses; income-tax deductions are then GST-exclusive.
   - GST on ride-sourcing is calculated on the FULL passenger fare (the GST-inclusive amount the passenger pays), NOT the smaller amount deposited after the platform takes its commission. Example: a $55 fare has $5 GST (1/11 of $55) even if Uber keeps $11 commission and pays you $44 — you still owe GST on the $55.
   - The platform's commission/service fee is a separate business expense you can deduct, and if you are GST-registered you can claim the GST credit on that commission (it reduces your net GST at 1B). So: declare the gross fare as income (GST at 1A), and claim the commission as an expense (GST credit at 1B).
   - Drivers doing BOTH rideshare and delivery under the same ABN: once you must register for GST because of the rideshare activity, your whole enterprise is GST-registered — GST then applies to your delivery income too, not just the passenger fares. The $75,000 delivery test no longer applies once you're registered.

E. RECORDS
   - Keep your logbook, odometer readings and receipts for 5 years.
   - Keep records of business km, platform statements and expense receipts.

F. INCOME
   - All income from every platform is assessable and must be declared, even cash or amounts below any threshold.
`;

export const US_KB = `=== UNITED STATES — IRS guidance for rideshare & delivery drivers (source of truth) ===

SOURCE: Internal Revenue Service (IRS) — Schedule C (Form 1040), Publication 463
(Travel, Gift, and Car Expenses), and the Gig Economy Tax Center.

A. CAR EXPENSE METHODS (choose ONE per car, per year)
1. Standard mileage rate
   - Rate: 67 cents per business mile for tax year 2024; 70 cents per mile for 2025. For 2026 the IRS set a split rate: 72.5 cents per mile for Jan 1–Jun 30, 2026 and 76 cents per mile for Jul 1–Dec 31, 2026 (a mid-year increase) — categorise each trip by its date. Updated by the IRS.
   - To use it, you generally must choose the standard mileage rate in the FIRST year the car is used for business; in later years you can switch to actual expenses (with restrictions). For a LEASED car, if you choose the standard mileage rate you must use it for the entire lease period.
   - The rate already includes gas, oil, maintenance, insurance and depreciation — you cannot deduct these separately.
2. Actual expense method
   - Deduct the business-use percentage of actual costs: gas, oil, repairs, maintenance, tires, insurance, registration/license, lease payments, and depreciation of the vehicle.

B. WHAT IS DEDUCTIBLE (business portion, reported on Schedule C)
   - Business miles via the standard mileage rate OR actual car expenses (see above).
   - Tolls and parking fees paid while working (deductible in addition to the standard mileage rate).
   - Cell phone — the business-use percentage of your plan and device.
   - Platform commissions and service fees (Uber/DoorDash/etc.).
   - Supplies used for the job: insulated/hot bags, phone mount, chargers, car cleaning (business portion), safety items.
   - Roadside assistance plans (business portion).
   - Health insurance premiums may be deductible as the self-employed health insurance deduction (taken on Form 1040, not Schedule C).
   - One-half of self-employment tax is deductible on Form 1040.

C. WHAT IS NOT DEDUCTIBLE
   - The personal-use portion of any expense.
   - Both methods at once, or car operating costs separately when using the standard mileage rate.
   - Traffic tickets, parking fines and other penalties.
   - Everyday clothing (only distinctive uniforms/protective gear qualify).
   - Meals for yourself while driving (personal). Business meals with a client can be 50% deductible, but that is uncommon for drivers.
   - Commuting/personal miles.

D. SELF-EMPLOYMENT & ESTIMATED TAX
   - Net profit from Schedule C is subject to self-employment tax of 15.3% (12.4% Social Security up to the annual wage base — $176,100 for 2025, $184,500 for 2026 — plus 2.9% Medicare with no cap), calculated on 92.35% of net profit, plus federal (and any state) income tax.
   - The single-filer standard deduction is $15,000 for 2025 and $16,100 for 2026 (OBBBA-adjusted). One-half of your self-employment tax is deductible when working out income tax.
   - You generally must pay estimated taxes quarterly using Form 1040-ES if you expect to owe $1,000 or more. 2026 due dates: Apr 15, Jun 15, Sep 15 (2026) and Jan 15 (2027).
   - A Form 1099-NEC or 1099-K from a platform reports income, but you must report ALL income even if you don't receive a form.

E. RECORDS
   - Keep a contemporaneous mileage log (date, business miles, purpose) and receipts.
   - Keep records generally for at least 3 years.
`;

export function kbFor(country: string): string {
  return (country || "").toUpperCase() === "US" ? US_KB : AU_KB;
}
